import SwiftUI
import QuickLookUI

/// Uses macOS Quick Look's native document generators so Office files retain
/// their original pagination, typography, tables, charts, slide layouts and images.
struct ScribeOfficePreview: NSViewRepresentable {
    let url: URL

    func makeNSView(context: Context) -> QLPreviewView {
        let view = QLPreviewView(frame: .zero, style: .normal)!
        view.autostarts = true
        view.previewItem = url as NSURL
        return view
    }

    func updateNSView(_ view: QLPreviewView, context: Context) {
        if (view.previewItem as? URL) != url {
            view.previewItem = url as NSURL
        }
    }
}
